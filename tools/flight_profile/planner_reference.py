#!/usr/bin/env python3
"""Reference cases for the station's apogee planner (backend/src/apogee_planner).

The planner flies a Rust port of flightsim.py. This script flies the same
cases through the Python model (gusts off, so the ascent is deterministic)
and writes backend/src/apogee_planner/fixtures/reference_cases.json; the Rust
test must agree with it (docs/apogee-planner.md section 1).

  python3 tools/flight_profile/planner_reference.py          # rewrite the fixture
  python3 tools/flight_profile/planner_reference.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import copy
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import flightsim as fs  # noqa: E402

OUT = HERE.parent.parent / 'backend' / 'src' / 'apogee_planner' / 'fixtures' / 'reference_cases.json'

CASES = [
    ('measured_motor', {}),
    ('measured_no_wind', {'environment.wind_mps': 0.0}),
    ('scaled_12000', {'motor.total_impulse_ns': 12000.0}),
    ('scaled_5000', {'motor.total_impulse_ns': 5000.0}),
    ('hot_windy', {'environment.temp_offset_k': 15.0, 'environment.wind_mps': 8.0, 'environment.wind_from_deg': 200.0}),
    ('cold_low_site', {'environment.temp_offset_k': -10.0, 'environment.site_msl_m': 200.0}),
    ('light_33kg_dry', {'vehicle.dry_mass_kg': 33.2}),
    ('no_boattail', {'vehicle.boattail_aft_diameter_m': None}),
    ('steep_rail', {'launch.tilt_deg': 2.0, 'launch.azimuth_deg': 0.0, 'motor.total_impulse_ns': 9000.0}),
]


def set_path(cfg, dotted, value):
    node = cfg
    keys = dotted.split('.')
    for k in keys[:-1]:
        node = node[k]
    assert keys[-1] in node, dotted
    node[keys[-1]] = value


def fly(overrides):
    cfg = json.loads((HERE / 'vehicle.json').read_text())
    cfg['environment']['gust_sigma_mps'] = 0.0
    for k, v in overrides.items():
        set_path(cfg, k, v)
    m = cfg['motor']
    motor = fs.Motor.load(HERE / m['thrust_curve_csv'], m['propellant_mass_kg'], m['nozzle_exit_diameter_m'],
                          m['total_impulse_ns'], m['oscillation_amplitude'], m['oscillation_hz'],
                          m.get('scale_propellant_with_impulse', False), m.get('impulse_scaling_thrust_exponent', 1.0))
    tr = fs.fly(cfg, random.Random(1), motor, record=False, stop_at_apogee=True)
    ev = tr.events
    return {
        'apogee_m': round(ev['apogee_m'], 2),
        'apogee_s': round(ev['apogee_s'] - cfg['launch']['ignition_s'], 3),
        'rail_exit_mps': round(ev['rail_exit_mps'], 3),
        'max_mach': round(tr.extra['max_mach'][0], 4),
        'impulse_ns': round(motor.impulse, 1),
        'prop_kg': round(motor.prop_kg, 4),
    }


def build():
    return {
        '_about': 'Generated by tools/flight_profile/planner_reference.py from flightsim.py and vehicle.json (gusts off). '
                  'apogee_s is from ignition. Do not edit by hand.',
        'cases': [{'name': n, 'overrides': o, 'expect': fly(o)} for n, o in CASES],
    }


def main(argv):
    data = build()
    text = json.dumps(data, indent=1) + '\n'
    if '--check' in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('reference_cases.json is stale: run tools/flight_profile/planner_reference.py')
            return 1
        return 0
    OUT.write_text(text)
    for c in data['cases']:
        print(c['name'], c['expect'])
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
